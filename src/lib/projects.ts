// Case study content. One entry per project page (/projects/[slug]); the page
// template (components/ProjectPage.tsx) renders whatever is here, so adding a
// case is data-only — no new layout work.

export type Paragraph = { text: string; strong?: boolean };

// Percent box for an image that's larger than / offset inside its frame
// (Figma crops two screens out of one tall export). Omit for plain cover.
export type ImageCrop = { left: string; top: string; width: string; height: string };

export type FigureImage = {
  src: string;
  alt: string;
  width: number;
  height: number;
  crop?: ImageCrop;
  // Animated screen recording shown inside a phone frame on top of the image.
  screen?: { src: string; alt: string };
};

export type ProjectBlock =
  // `title` is left out on blocks that continue the section above them.
  | { kind: "text"; title?: string; paragraphs: Paragraph[] }
  | { kind: "steps"; title?: string; intro?: Paragraph[]; steps: { title: string; text: string }[] }
  // Without `image`, the figure renders as a labelled placeholder frame.
  | { kind: "figure"; image?: FigureImage; placeholder?: string; caption?: string }
  | { kind: "figure-pair"; items: { image: FigureImage; caption: string }[] };

export type ProjectMeta = {
  label: string;
  value?: string;
  links?: { label: string; href: string }[];
};

export type Project = {
  slug: string;
  title: string;
  // One-line summary shown under the title (optional).
  subtitle?: string;
  description: string;
  meta: ProjectMeta[];
  metrics: { value: string; label: string }[];
  // Three equal stat columns on desktop (default is the LU Cards Figma widths).
  fluidMetrics?: boolean;
  blocks: ProjectBlock[];
  // "Следующий проект" target. Falls back to the works grid until the next
  // case page exists.
  nextHref: string;
};

