// ── English ────────────────────────────────────────────────────────────────
// The English copy (lib/projects.en.ts) is plain text in the same block order.
// localizeProject() lays it over the Russian structure, so images, links and
// layout are shared and a missing or extra block fails the build instead of
// silently drifting.

export type BlockText =
  | { kind: "text"; title?: string; paragraphs: string[] }
  | { kind: "steps"; title?: string; intro?: string[]; steps: { title: string; text: string }[] }
  | { kind: "figure"; placeholder?: string; caption?: string; alt?: string }
  | { kind: "figure-pair"; items: { caption: string; alt?: string; screenAlt?: string }[] };

export type ProjectText = {
  title: string;
  description: string;
  meta: { label: string; value?: string }[];
  metrics: { value: string; label: string }[];
  summary?: Summary;
  blocks: BlockText[];
};

export function localizeProject(base: Project, text: ProjectText): Project {
  const fail = (msg: string): never => {
    throw new Error(`projects.en.ts → ${base.slug}: ${msg}`);
  };
  if (text.meta.length !== base.meta.length) fail("meta length differs");
  if (text.metrics.length !== base.metrics.length) fail("metrics length differs");
  if (text.blocks.length !== base.blocks.length) {
    fail(`has ${text.blocks.length} blocks, the Russian original has ${base.blocks.length}`);
  }

  const blocks = base.blocks.map((b, i): ProjectBlock => {
    const t = text.blocks[i];
    if (t.kind !== b.kind) fail(`block ${i} is "${t.kind}", expected "${b.kind}"`);
    switch (b.kind) {
      case "text": {
        const tt = t as Extract<BlockText, { kind: "text" }>;
        if (tt.paragraphs.length !== b.paragraphs.length) fail(`block ${i}: paragraph count differs`);
        if (!!tt.title !== !!b.title) fail(`block ${i}: title presence differs`);
        return { ...b, title: tt.title, paragraphs: b.paragraphs.map((p, k) => ({ ...p, text: tt.paragraphs[k] })) };
      }
      case "steps": {
        const tt = t as Extract<BlockText, { kind: "steps" }>;
        if (tt.steps.length !== b.steps.length) fail(`block ${i}: step count differs`);
        if (!!tt.title !== !!b.title) fail(`block ${i}: title presence differs`);
        if ((tt.intro?.length ?? 0) !== (b.intro?.length ?? 0)) fail(`block ${i}: intro count differs`);
        return {
          ...b,
          title: tt.title,
          intro: b.intro?.map((p, k) => ({ ...p, text: tt.intro![k] })),
          steps: tt.steps,
        };
      }
      case "figure": {
        const tt = t as Extract<BlockText, { kind: "figure" }>;
        if (!!b.placeholder !== !!tt.placeholder) fail(`block ${i}: placeholder presence differs`);
        if (!!b.caption !== !!tt.caption) fail(`block ${i}: caption presence differs`);
        if (b.image && !tt.alt) fail(`block ${i}: missing alt text`);
        return {
          ...b,
          placeholder: tt.placeholder,
          caption: tt.caption,
          image: b.image && { ...b.image, alt: tt.alt! },
        };
      }
      case "figure-pair": {
        const tt = t as Extract<BlockText, { kind: "figure-pair" }>;
        if (tt.items.length !== b.items.length) fail(`block ${i}: item count differs`);
        return {
          ...b,
          items: b.items.map((it, k) => ({
            caption: tt.items[k].caption,
            image: {
              ...it.image,
              alt: tt.items[k].alt ?? it.image.alt,
              screen: it.image.screen && {
                ...it.image.screen,
                alt: tt.items[k].screenAlt ?? it.image.screen.alt,
              },
            },
          })),
        };
      }
    }
  });

  return {
    ...base,
    title: text.title,
    description: text.description,
    meta: base.meta.map((m, k) => ({ ...m, label: text.meta[k].label, value: m.value !== undefined ? text.meta[k].value : undefined })),
    metrics: text.metrics,
    summary: text.summary ?? base.summary,
    blocks,
  };
}

export function getProject(slug: string, lang: Lang = "ru"): Project | undefined {
  const base = projects.find((p) => p.slug === slug);
  if (!base || lang === "ru") return base;
  const text = projectsEn[slug];
  if (!text) throw new Error(`projects.en.ts: no English text for "${slug}"`);
  return localizeProject(base, text);
}
